from datetime import datetime
import enum
from sqlalchemy import Column, Integer, String, Text, Float, Boolean, DateTime, ForeignKey, Enum as SQLEnum, JSON
from sqlalchemy.orm import relationship
from app.db.base_class import Base


class ModelProviderType(str, enum.Enum):
    TRAINED_ML = "TRAINED_ML"
    STATISTICAL_MODEL = "STATISTICAL_MODEL"
    RULE_BASED = "RULE_BASED"
    FALLBACK_SIMULATION = "FALLBACK_SIMULATION"


class AIRiskLevel(str, enum.Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AIAlertSeverity(str, enum.Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class AIAlertStatus(str, enum.Enum):
    ACTIVE = "ACTIVE"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"
    DISMISSED = "DISMISSED"


class AIPredictionType(str, enum.Enum):
    QUEUE_WAIT_TIME = "QUEUE_WAIT_TIME"
    BED_OCCUPANCY = "BED_OCCUPANCY"
    PHARMACY_DEPLETION = "PHARMACY_DEPLETION"
    TRIAGE_ASSESSMENT = "TRIAGE_ASSESSMENT"
    ANOMALY_DETECTION = "ANOMALY_DETECTION"
    CLINICAL_SUMMARY = "CLINICAL_SUMMARY"


class AIAlertType(str, enum.Enum):
    OPD_DELAY = "OPD_DELAY"
    BED_CAPACITY_RISK = "BED_CAPACITY_RISK"
    PHARMACY_DEPLETION = "PHARMACY_DEPLETION"
    EMERGENCY_SURGE = "EMERGENCY_SURGE"
    LAB_BACKLOG = "LAB_BACKLOG"
    OPERATIONAL_ANOMALY = "OPERATIONAL_ANOMALY"


class AIPrediction(Base):
    """Traceable AI prediction record capturing model inputs, outputs, risk, and explanations."""
    __tablename__ = "ai_predictions"

    id = Column(Integer, primary_key=True, index=True)
    prediction_type = Column(SQLEnum(AIPredictionType), nullable=False, index=True)
    entity_type = Column(String(50), nullable=False, index=True)  # e.g., DEPARTMENT, WARD, MEDICINE, CASE
    entity_id = Column(String(50), nullable=True, index=True)
    prediction_value = Column(JSON, nullable=False)  # Numeric or structured prediction payload
    risk_level = Column(SQLEnum(AIRiskLevel), nullable=False, default=AIRiskLevel.LOW)
    confidence = Column(Float, nullable=True)  # Meaningful confidence or None if rule-based
    model_name = Column(String(100), nullable=False, default="carex-hybrid-engine")
    model_version = Column(String(50), nullable=False, default="v1.0.0")
    model_provider_type = Column(SQLEnum(ModelProviderType), nullable=False, default=ModelProviderType.STATISTICAL_MODEL)
    
    explanation = Column(JSON, nullable=False)  # Structured "Why?" bullet points list
    recommended_action = Column(Text, nullable=False)
    input_features = Column(JSON, nullable=True)  # Snapshot of inputs used for reproducibility
    generated_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)

    # Relationships
    feedbacks = relationship("AIFeedback", back_populates="prediction", cascade="all, delete-orphan")


class AIAlert(Base):
    """Operational and clinical alert generated by the AI Intelligence Layer."""
    __tablename__ = "ai_alerts"

    id = Column(Integer, primary_key=True, index=True)
    alert_type = Column(SQLEnum(AIAlertType), nullable=False, index=True)
    severity = Column(SQLEnum(AIAlertSeverity), nullable=False, default=AIAlertSeverity.WARNING, index=True)
    title = Column(String(200), nullable=False)
    description = Column(Text, nullable=False)
    reason = Column(JSON, nullable=False)  # Explanatory factors
    recommended_action = Column(Text, nullable=False)
    
    related_entity = Column(String(50), nullable=False)  # e.g., OPD, BED, PHARMACY, EMERGENCY
    related_entity_id = Column(String(50), nullable=True)
    status = Column(SQLEnum(AIAlertStatus), nullable=False, default=AIAlertStatus.ACTIVE, index=True)
    
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False, index=True)
    acknowledged_at = Column(DateTime, nullable=True)
    acknowledged_by_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    resolved_at = Column(DateTime, nullable=True)
    resolved_by_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)

    # Relationships
    acknowledged_by = relationship("User", foreign_keys=[acknowledged_by_id])
    resolved_by = relationship("User", foreign_keys=[resolved_by_id])
    feedbacks = relationship("AIFeedback", back_populates="alert", cascade="all, delete-orphan")


class AIFeedback(Base):
    """User feedback on AI outputs for tracking utility and future model calibration."""
    __tablename__ = "ai_feedbacks"

    id = Column(Integer, primary_key=True, index=True)
    prediction_id = Column(Integer, ForeignKey("ai_predictions.id", ondelete="CASCADE"), nullable=True)
    alert_id = Column(Integer, ForeignKey("ai_alerts.id", ondelete="CASCADE"), nullable=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    rating = Column(String(20), nullable=False)  # USEFUL, NOT_USEFUL, INCORRECT, NEEDS_REVIEW
    notes = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    # Relationships
    prediction = relationship("AIPrediction", back_populates="feedbacks")
    alert = relationship("AIAlert", back_populates="feedbacks")
    user = relationship("User")


class AIDocumentRecord(Base):
    """Clinical document processed by Medical Document Intelligence."""
    __tablename__ = "ai_document_records"

    id = Column(Integer, primary_key=True, index=True)
    file_name = Column(String(255), nullable=False)
    file_type = Column(String(50), nullable=False)  # PDF, JPG, PNG
    patient_id = Column(Integer, ForeignKey("patients.id", ondelete="SET NULL"), nullable=True)
    uploaded_by_id = Column(Integer, ForeignKey("users.id", ondelete="RESTRICT"), nullable=False)
    
    document_type = Column(String(100), nullable=False, default="LABORATORY_REPORT")
    raw_text = Column(Text, nullable=True)
    extracted_data = Column(JSON, nullable=False)  # Structured parameters, values, units, reference ranges
    ai_summary = Column(Text, nullable=False)
    confidence = Column(Float, nullable=True)
    
    is_verified = Column(Boolean, default=False, nullable=False)
    verified_by_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    verified_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    # Relationships
    patient = relationship("Patient")
    uploaded_by = relationship("User", foreign_keys=[uploaded_by_id])
    verified_by = relationship("User", foreign_keys=[verified_by_id])


class AIShiftHandover(Base):
    """Structured AI-assisted nursing shift handover document."""
    __tablename__ = "ai_shift_handovers"

    id = Column(Integer, primary_key=True, index=True)
    ward_id = Column(Integer, ForeignKey("wards.id", ondelete="SET NULL"), nullable=True)
    shift_name = Column(String(50), nullable=False)  # MORNING, EVENING, NIGHT
    from_nurse_id = Column(Integer, ForeignKey("users.id", ondelete="RESTRICT"), nullable=False)
    to_nurse_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    
    patient_summaries = Column(JSON, nullable=False)  # List of patient cards: vitals, pending, alerts, tasks
    important_observations = Column(Text, nullable=True)
    next_shift_checklist = Column(JSON, nullable=False)  # Actionable items checklist
    ai_notes = Column(Text, nullable=False)
    
    status = Column(String(20), nullable=False, default="DRAFT")  # DRAFT, REVIEWED, APPROVED
    approved_by_id = Column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    approved_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    # Relationships
    ward = relationship("Ward")
    from_nurse = relationship("User", foreign_keys=[from_nurse_id])
    to_nurse = relationship("User", foreign_keys=[to_nurse_id])
    approved_by = relationship("User", foreign_keys=[approved_by_id])
